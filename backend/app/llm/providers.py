"""LLM Provider interfaces and implementations.

Supports:
- Anthropic as default provider (official SDK or direct API)
- Pluggable OpenAI-compatible provider
- MockProvider for deterministic test suites
"""

from __future__ import annotations

import json
import logging
from abc import ABC, abstractmethod
from typing import Any

from pydantic import BaseModel, Field

from app.core.config import settings
from app.llm.schemas import LLMError, LLMRateLimitError, LLMTimeoutError

logger = logging.getLogger(__name__)


class LLMResponse(BaseModel):
    """Structured response container from any provider."""

    content: str = Field(..., description="Raw text or JSON generated by the model")
    prompt_tokens: int = Field(default=0, description="Tokens consumed by input prompt")
    completion_tokens: int = Field(default=0, description="Tokens generated by model")
    cost_usd: float = Field(default=0.0, description="Estimated total cost in USD")
    raw_model: str = Field(default="", description="Model identifier used for generation")


def estimate_cost(model: str, prompt_tokens: int, completion_tokens: int) -> float:
    """Calculate estimated cost in USD based on model pricing."""
    model_lower = model.lower()
    if "claude-3-5-sonnet" in model_lower:
        # Anthropic: $3.00/MTok input, $15.00/MTok output
        cost = (prompt_tokens * 0.000003) + (completion_tokens * 0.000015)
    elif "claude-3-haiku" in model_lower or "claude-3-5-haiku" in model_lower:
        cost = (prompt_tokens * 0.0000008) + (completion_tokens * 0.000004)
    elif "gpt-4o-mini" in model_lower:
        # OpenAI: $0.15/MTok input, $0.60/MTok output
        cost = (prompt_tokens * 0.00000015) + (completion_tokens * 0.0000006)
    elif "gpt-4o" in model_lower:
        cost = (prompt_tokens * 0.0000025) + (completion_tokens * 0.00001)
    else:
        # Conservative baseline fallback
        cost = (prompt_tokens * 0.000001) + (completion_tokens * 0.000003)
    return round(cost, 6)


class BaseLLMProvider(ABC):
    """Abstract interface for LLM provider adapters."""

    name: str = "base"

    @abstractmethod
    def generate(
        self,
        prompt: str,
        *,
        system: str = "",
        model: str | None = None,
        max_tokens: int = 2000,
        temperature: float = 0.0,
        timeout_seconds: float = 30.0,
    ) -> LLMResponse:
        """Execute text completion and return unified LLMResponse."""
        ...


class AnthropicProvider(BaseLLMProvider):
    """Anthropic Claude provider adapter (Default)."""

    name: str = "anthropic"

    def __init__(self, api_key: str | None = None, base_url: str | None = None):
        self.api_key = api_key or settings.LLM_API_KEY
        self.base_url = base_url

    def generate(
        self,
        prompt: str,
        *,
        system: str = "",
        model: str | None = None,
        max_tokens: int = 2000,
        temperature: float = 0.0,
        timeout_seconds: float = 30.0,
    ) -> LLMResponse:
        active_model = model or settings.LLM_MODEL
        if not self.api_key:
            raise LLMError("Anthropic API key is not configured")

        # 1. Try official Anthropic SDK first
        try:
            import anthropic  # type: ignore

            client = anthropic.Anthropic(
                api_key=self.api_key,
                base_url=self.base_url,
                timeout=timeout_seconds,
            )
            response = client.messages.create(
                model=active_model,
                max_tokens=max_tokens,
                temperature=temperature,
                system=system if system else anthropic.NOT_GIVEN,
                messages=[{"role": "user", "content": prompt}],
            )
            content = ""
            for block in response.content:
                if getattr(block, "type", "") == "text":
                    content += block.text

            p_toks = getattr(response.usage, "input_tokens", 0)
            c_toks = getattr(response.usage, "output_tokens", 0)
            cost = estimate_cost(active_model, p_toks, c_toks)
            return LLMResponse(
                content=content,
                prompt_tokens=p_toks,
                completion_tokens=c_toks,
                cost_usd=cost,
                raw_model=active_model,
            )
        except ImportError:
            pass  # Fall back to httpx below
        except Exception as exc:
            err_str = str(exc).lower()
            if "timeout" in err_str:
                raise LLMTimeoutError(f"Anthropic call timed out: {exc}") from exc
            if "rate_limit" in err_str or "429" in err_str:
                raise LLMRateLimitError(f"Anthropic rate limit: {exc}") from exc
            raise LLMError(f"Anthropic generation error: {exc}") from exc

        # 2. Direct HTTP via httpx fallback
        import httpx

        headers = {
            "x-api-key": self.api_key,
            "anthropic-version": "2023-06-01",
            "content-type": "application/json",
        }
        body: dict[str, Any] = {
            "model": active_model,
            "max_tokens": max_tokens,
            "temperature": temperature,
            "messages": [{"role": "user", "content": prompt}],
        }
        if system:
            body["system"] = system

        url = (self.base_url or "https://api.anthropic.com").rstrip("/") + "/v1/messages"
        try:
            with httpx.Client(timeout=timeout_seconds) as client:
                res = client.post(url, headers=headers, json=body)
                if res.status_code == 429:
                    raise LLMRateLimitError(f"Anthropic 429 Rate Limit: {res.text}")
                res.raise_for_status()
                data = res.json()
                content = "".join(
                    b["text"] for b in data.get("content", []) if b.get("type") == "text"
                )
                usage = data.get("usage", {})
                p_toks = usage.get("input_tokens", 0)
                c_toks = usage.get("output_tokens", 0)
                return LLMResponse(
                    content=content,
                    prompt_tokens=p_toks,
                    completion_tokens=c_toks,
                    cost_usd=estimate_cost(active_model, p_toks, c_toks),
                    raw_model=active_model,
                )
        except httpx.TimeoutException as exc:
            raise LLMTimeoutError(f"Anthropic HTTP call timed out: {exc}") from exc
        except Exception as exc:
            raise LLMError(f"Anthropic HTTP request error: {exc}") from exc


class OpenAICompatibleProvider(BaseLLMProvider):
    """OpenAI and OpenAI-compatible API provider adapter."""

    name: str = "openai"

    def __init__(self, api_key: str | None = None, base_url: str | None = None):
        self.api_key = api_key or settings.LLM_API_KEY
        self.base_url = base_url or getattr(settings, "LLM_BASE_URL", "")

    def generate(
        self,
        prompt: str,
        *,
        system: str = "",
        model: str | None = None,
        max_tokens: int = 2000,
        temperature: float = 0.0,
        timeout_seconds: float = 30.0,
    ) -> LLMResponse:
        active_model = model or settings.LLM_MODEL
        if not self.api_key:
            raise LLMError("OpenAI API key is not configured")

        # 1. Try official openai SDK
        try:
            import openai  # type: ignore

            client_kwargs: dict[str, Any] = {
                "api_key": self.api_key,
                "timeout": timeout_seconds,
            }
            if self.base_url:
                client_kwargs["base_url"] = self.base_url
            client = openai.OpenAI(**client_kwargs)

            messages: list[dict[str, str]] = []
            if system:
                messages.append({"role": "system", "content": system})
            messages.append({"role": "user", "content": prompt})

            res = client.chat.completions.create(
                model=active_model,
                messages=messages,
                max_tokens=max_tokens,
                temperature=temperature,
            )
            content = res.choices[0].message.content or ""
            p_toks = res.usage.prompt_tokens if res.usage else 0
            c_toks = res.usage.completion_tokens if res.usage else 0
            return LLMResponse(
                content=content,
                prompt_tokens=p_toks,
                completion_tokens=c_toks,
                cost_usd=estimate_cost(active_model, p_toks, c_toks),
                raw_model=active_model,
            )
        except ImportError:
            pass
        except Exception as exc:
            err_str = str(exc).lower()
            if "timeout" in err_str:
                raise LLMTimeoutError(f"OpenAI call timed out: {exc}") from exc
            if "rate_limit" in err_str or "429" in err_str:
                raise LLMRateLimitError(f"OpenAI rate limit: {exc}") from exc
            raise LLMError(f"OpenAI error: {exc}") from exc

        # 2. Direct HTTP via httpx fallback
        import httpx

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        messages = []
        if system:
            messages.append({"role": "system", "content": system})
        messages.append({"role": "user", "content": prompt})

        payload = {
            "model": active_model,
            "messages": messages,
            "max_tokens": max_tokens,
            "temperature": temperature,
        }
        url = (self.base_url or "https://api.openai.com/v1").rstrip("/") + "/chat/completions"
        try:
            with httpx.Client(timeout=timeout_seconds) as client:
                res = client.post(url, headers=headers, json=payload)
                if res.status_code == 429:
                    raise LLMRateLimitError(f"OpenAI 429 Rate Limit: {res.text}")
                res.raise_for_status()
                data = res.json()
                content = data["choices"][0]["message"]["content"]
                usage = data.get("usage", {})
                p_toks = usage.get("prompt_tokens", 0)
                c_toks = usage.get("completion_tokens", 0)
                return LLMResponse(
                    content=content,
                    prompt_tokens=p_toks,
                    completion_tokens=c_toks,
                    cost_usd=estimate_cost(active_model, p_toks, c_toks),
                    raw_model=active_model,
                )
        except httpx.TimeoutException as exc:
            raise LLMTimeoutError(f"OpenAI HTTP timeout: {exc}") from exc
        except Exception as exc:
            raise LLMError(f"OpenAI HTTP error: {exc}") from exc


class MockProvider(BaseLLMProvider):
    """Configurable mock provider for test suites."""

    name: str = "mock"

    def __init__(
        self,
        responses: list[str] | None = None,
        *,
        fail_with_invalid_json: int = 0,
        fail_with_ungrounded: int = 0,
        raise_timeout: bool = False,
        raise_rate_limit: bool = False,
    ):
        self.responses = list(responses or [])
        self.fail_with_invalid_json = fail_with_invalid_json
        self.fail_with_ungrounded = fail_with_ungrounded
        self.raise_timeout = raise_timeout
        self.raise_rate_limit = raise_rate_limit
        self.call_count = 0
        self.call_history: list[dict[str, Any]] = []

    def generate(
        self,
        prompt: str,
        *,
        system: str = "",
        model: str | None = None,
        max_tokens: int = 2000,
        temperature: float = 0.0,
        timeout_seconds: float = 30.0,
    ) -> LLMResponse:
        self.call_count += 1
        active_model = model or settings.LLM_MODEL
        self.call_history.append({"prompt": prompt, "system": system, "model": active_model})

        if self.raise_timeout:
            raise LLMTimeoutError("Mock provider simulated timeout")

        if self.raise_rate_limit:
            raise LLMRateLimitError("Mock provider simulated rate limit")

        if self.fail_with_invalid_json > 0:
            self.fail_with_invalid_json -= 1
            return LLMResponse(
                content="Not valid JSON {{{ incomplete",
                prompt_tokens=40,
                completion_tokens=10,
                cost_usd=0.0001,
                raw_model=active_model,
            )

        if self.fail_with_ungrounded > 0:
            self.fail_with_ungrounded -= 1
            # Return JSON with made-up numbers (e.g. 999999999) that violate grounding
            bad_data = {
                "summary_en": "Total ungrounded figure was 999999999 PKR.",
                "summary_ur": "غیر مصدقہ تفصیل۔",
                "strengths": ["Strong flow of 999999999 PKR"],
                "weaknesses": ["None"],
                "recommendation_rationale": "High score of 999999999.",
                "fact_ids_cited": [],
            }
            return LLMResponse(
                content=json.dumps(bad_data),
                prompt_tokens=50,
                completion_tokens=40,
                cost_usd=0.0002,
                raw_model=active_model,
            )

        content = self.responses.pop(0) if self.responses else "{}"

        return LLMResponse(
            content=content,
            prompt_tokens=60,
            completion_tokens=50,
            cost_usd=0.0003,
            raw_model=active_model,
        )


def get_provider(name: str | None = None) -> BaseLLMProvider:
    """Provider factory based on settings or explicit name."""
    provider_name = (name or settings.LLM_PROVIDER).lower()
    if provider_name == "anthropic":
        return AnthropicProvider()
    elif provider_name in {"openai", "openai-compatible", "openai_compatible"}:
        return OpenAICompatibleProvider()
    elif provider_name == "mock":
        return MockProvider()
    else:
        logger.warning("Unrecognized LLM provider '%s', defaulting to Anthropic", provider_name)
        return AnthropicProvider()
